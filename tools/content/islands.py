def level(id, title, mode, skills, count, intro, outro, reward=None, blurb="", table=None):
    """`table`: a level whose dialogue names one times table asks only that table, when the
    grown-up has it switched on."""
    d = {"id": id, "title": title, "mode": mode, "skills": skills, "count": count,
         "intro": intro, "outro": outro, "reward": reward, "blurb": blurb}
    if table: d["table"] = table
    return d

